"""Конструкторы промптов для AI-запросов. На русском. Личность бота — Марк."""

from datetime import datetime
import pytz

from config import TIMEZONE


_tz = pytz.timezone(TIMEZONE)


MARK_PERSONA = (
    "Тебя зовут Марк. Ты — мой друг и личный новостной аналитик. "
    "Говоришь со мной на равных, прямо, как друг, без поддержки, без каких-то лишних слов. Ты сам по себе спокоен, лаконичен. Смелый: не сглаживаешь углы, "
    "не виляешь, если факты неудобные — называешь их. Никаких реверансов, "
    "никаких «давайте разберём», никаких «вот сводка». Сразу к делу, по фактам, "
    "со ссылками. Если в чём-то не уверен — так и говоришь."
)

TELEGRAM_HTML_RULES = (
    "ФОРМАТ: Telegram HTML. Можно ТОЛЬКО эти теги: <b>, <i>, <a href=\"...\">, <code>, <pre>, <blockquote>. "
    "ЗАПРЕЩЕНО: <ul>, <ol>, <li>, <h1>-<h6>, <p>, <div>, <br>, <span>, markdown (**, ##, ---). "
    "Списки делай через • в начале строки и переносы. Заголовки — через <b>. Никаких HTML-сущностей кроме &amp;, &lt;, &gt;."
)


def _now() -> str:
    return datetime.now(_tz).strftime("%d.%m.%Y %H:%M")


def _format_posts_block(posts: list[dict], max_chars_per_post: int = 400) -> str:
    """Сериализует список постов из БД в текстовый блок для prompt'а."""
    if not posts:
        return "(нет постов в базе по теме)"
    lines = []
    for i, p in enumerate(posts, 1):
        text = " ".join(p["text"].split())
        if len(text) > max_chars_per_post:
            text = text[: max_chars_per_post - 1] + "…"
        when = p["posted_at"].astimezone(_tz).strftime("%d.%m %H:%M")
        lines.append(
            f'[{i}] {p["channel_username"]} ({p["channel_type"]}, {when})\n{text}\nlink: {p["link"]}'
        )
    return "\n\n".join(lines)


# ---------- /digest по темам ----------

def _format_news_with_experts(news_posts: list[dict], expert_links: dict[int, list[dict]]) -> str:
    """Формат: каждая news + (опционально) привязанные мнения экспертов."""
    if not news_posts:
        return "(новостных постов нет)"
    out = []
    for i, p in enumerate(news_posts, 1):
        text = " ".join(p["text"].split())
        if len(text) > 400:
            text = text[:399] + "…"
        when = p["posted_at"].strftime("%d.%m %H:%M")
        block = [f'[N{i}] {p["channel_username"]} ({when})\n{text}\nlink: {p["link"]}']
        for ep in expert_links.get(p["id"], []):
            etext = " ".join(ep["text"].split())
            if len(etext) > 250:
                etext = etext[:249] + "…"
            ewhen = ep["posted_at"].strftime("%d.%m %H:%M")
            block.append(
                f'  └─ EXPERT-LINK {ep["channel_username"]} ({ewhen}): {etext}\n     link: {ep["link"]}'
            )
        out.append("\n".join(block))
    return "\n\n".join(out)


def build_digest_prompt(
    news_posts: list[dict],
    expert_links: dict[int, list[dict]],
    unlinked_experts: list[dict],
    hours: int,
    total_posts: int,
) -> str:
    news_block = _format_news_with_experts(news_posts, expert_links)
    experts_extra = _format_posts_block(unlinked_experts, max_chars_per_post=300) if unlinked_experts else "(нет)"

    return f"""{MARK_PERSONA}

{TELEGRAM_HTML_RULES}

Сейчас {_now()}. Сделай мне тематический дайджест за {hours} ч. В базе {total_posts} постов, ниже — приоритизированный набор.

Правила:
- Группируй сам по содержанию (Политика, Экономика, Конфликты, Технологии, Общество и т.п.). 3-7 групп.
- Каждую группу начинай с эмодзи + <b>Название сферы</b>.
- Внутри группы — 2-5 тезисов в формате:
  • [Суть события одной строкой] — <a href="link">@канал</a> [ещё ссылки если есть]
- Если у news-поста есть EXPERT-LINK (комментарий эксперта рядом) — добавь подстроку курсивом сразу после тезиса:
  <i>💬 <a href="link">@эксперт</a>: «короткий пересказ или цитата»</i>
- В самом конце — блок «<b>💬 Общие мнения экспертов</b>» для эксперт-постов, не привязанных к новостям (раздел «unlinked experts»). 1-3 тезиса. Нет — пропусти.
- HTML-разметка Telegram: <b>, <i>, <a href="...">. Никакого markdown.
- В дайджесте — только факты. Никаких 🤖 блоков и личного мнения здесь.

NEWS (с привязанными мнениями экспертов под каждой, если есть):

{news_block}

UNLINKED EXPERTS (общие мнения без привязки к конкретной новости):

{experts_extra}
"""


